# Funciones:
# Suma:
def suma(n1, n2):
    return n1 + n2

# Resta:
def resta(n1, n2):
    return n1 - n2

# Multiplicacion:
def mult(n1, n2):
    return n1 * n2

# Division:
def div(n1, n2):
    return n1 / n2

# Modulo:
def mod(n1, n2):
    return n1 % n2

# Potencia:
def poW(n1, n2):
    return n1 ** n2

